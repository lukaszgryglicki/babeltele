#!/usr/bin/env python3
"""Generate src/tokcost.rs: BPE token costs of every lexicon string.

    cargo build --release
    target/release/babeltele --dump-lexicon | scripts/gen_tokcost.py > src/tokcost.rs

Each line of the dump is one string in its rendered form (" word" for spaced
items, bare for glued ones). The table stores (string, o200k_base tokens,
cl100k_base tokens), sorted for binary search. Requires `pip install tiktoken`.
"""
import sys
import tiktoken

o200k = tiktoken.get_encoding("o200k_base")
cl100k = tiktoken.get_encoding("cl100k_base")

def cost(enc, s):
    return min(255, len(enc.encode(s, disallowed_special=())))

def rust_str(s):
    out = []
    for ch in s:
        if ch == '"' or ch == '\\':
            out.append('\\' + ch)
        elif ord(ch) < 0x20 or ch == '\x7f':
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'

keys = sorted({line.rstrip("\n") for line in sys.stdin if line.strip()})
# Rust's str ordering is byte-wise, Python's is by code point; both agree for UTF-8.
sys.stdout.write("//! Generated by scripts/gen_tokcost.py — do not edit.\n")
sys.stdout.write("//! (rendered string, o200k_base tokens, cl100k_base tokens), sorted by string.\n")
sys.stdout.write("#[rustfmt::skip]\n")
sys.stdout.write(f"pub static COSTS: &[(&str, u8, u8)] = &[ // {len(keys)} entries\n")
for k in keys:
    sys.stdout.write(f"    ({rust_str(k)}, {cost(o200k, k)}, {cost(cl100k, k)}),\n")
sys.stdout.write("];\n")
